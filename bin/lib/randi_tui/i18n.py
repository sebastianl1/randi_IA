def lang_code(value: str) -> str:
    return "en" if value == "en" else "es"


def tr(lang: str, key: str, default: str = "") -> str:
    d = T.get(lang, T["es"])
    return d.get(key, default or T["es"].get(key, key))


def slash_desc(lang: str, command: str) -> str:
    d = T.get(lang, T["es"]).get("slash", {})
    return d.get(command, command)
